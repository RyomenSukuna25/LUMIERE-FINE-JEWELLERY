import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import jewel
from catalog import C
root = os.path.join(os.path.dirname(__file__), '..')
out = os.path.join(root, 'public/images/products'); os.makedirs(out, exist_ok=True)
data = []
for (pid, name, cat, kind, design, stn, metal, price, cmp_, mat, stl, tags, best, new, feat, blurb) in C:
    key = 'pendant' if cat == 'Pendants' else None
    for v in 'abc':
        svg = jewel.render_view(pid, kind, design, stn, metal, v, key)
        open(os.path.join(out, f'{pid}-{v}.svg'), 'w').write(svg)
    data.append(dict(id=pid, name=name, category=cat, kind=kind, design=design, stone=stl, metal=metal, price=price, compareAtPrice=cmp_, material=mat, tags=tags, bestseller=bool(best), newArrival=bool(new), featured=bool(feat), description=blurb))
json.dump(data, open(os.path.join(root, 'src/data/products.generated.json'), 'w'), ensure_ascii=False, indent=1)
open(os.path.join(root, 'src/data/products.generated.js'), 'w').write('// AUTO-GENERATED by tools/build_images.py — do not edit\nexport default ' + json.dumps(data, ensure_ascii=False, indent=1) + '\n')
print(len(data), 'products,', len(data) * 3, 'images')
